// Generates supabase/seed_checklist.sql from src/data/checklist.js.
// Run:  npm run db:seed   then paste the output file into the Supabase SQL editor.
// Re-run whenever you add checklist items (existing reviews keep their answers).
import { writeFileSync } from 'node:fs'
import { LISTS } from '../src/data/checklist.js'

const rows = Object.entries(LISTS).flatMap(([list, l]) => l.items.map((i) => `('${i.id}','${list}','${i.pri}')`))
const sql = `-- GENERATED by scripts/gen-seed.mjs – do not edit by hand.
insert into checklist_items (id, list, priority) values
${rows.join(',\n')}
on conflict (id) do update set list = excluded.list, priority = excluded.priority;
`
writeFileSync(new URL('../supabase/seed_checklist.sql', import.meta.url), sql)
console.log(`Wrote ${rows.length} checklist rows to supabase/seed_checklist.sql`)
